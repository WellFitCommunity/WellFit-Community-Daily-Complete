#!/usr/bin/env node
/**
 * Guardian tool-signing key generation — RUN ONCE, LOCALLY, BY MARIA.
 *
 *   node scripts/guardian-generate-signing-key.mjs
 *
 * Prints the PRIVATE JWK to stdout — store it in your password manager and as
 * the GitHub Actions secret GUARDIAN_SIGNING_KEY. It is NEVER written to disk
 * or committed. The matching PUBLIC key is written into
 * src/services/guardian-agent/guardianSigningKey.ts (committed — public by
 * definition).
 *
 * After running: commit the guardianSigningKey.ts change, then run
 *   GUARDIAN_SIGNING_KEY='<private jwk json>' node scripts/guardian-sign-tools.mjs
 * to sign the first-party tools.
 */

import { webcrypto } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import process from 'node:process';

const { subtle } = webcrypto;

const keyPair = await subtle.generateKey(
  { name: 'ECDSA', namedCurve: 'P-256' },
  true,
  ['sign', 'verify']
);

const privateJwk = await subtle.exportKey('jwk', keyPair.privateKey);
const publicJwk = await subtle.exportKey('jwk', keyPair.publicKey);
const keyId = `guardian-es256-${new Date().toISOString().slice(0, 10)}`;

const moduleSource = `/**
 * Guardian tool-signing PUBLIC key (ES256 / ECDSA P-256 JWK).
 *
 * Generated by scripts/guardian-generate-signing-key.mjs — the private key is
 * NOT in this repo (password manager + GUARDIAN_SIGNING_KEY Actions secret).
 * Public keys are safe to commit.
 *
 * Copyright (c) 2025-2026 Envision Virtual Edge Group LLC. All rights reserved.
 */

export interface GuardianSigningPublicKey {
  keyId: string;
  jwk: JsonWebKey;
}

export const GUARDIAN_SIGNING_PUBLIC_KEY: GuardianSigningPublicKey | null = {
  keyId: '${keyId}',
  jwk: ${JSON.stringify(publicJwk, null, 2)},
};
`;

writeFileSync('src/services/guardian-agent/guardianSigningKey.ts', moduleSource);

process.stdout.write('\n=== PRIVATE KEY (store in password manager + GUARDIAN_SIGNING_KEY secret; NEVER commit) ===\n');
process.stdout.write(JSON.stringify({ keyId, jwk: privateJwk }) + '\n');
process.stdout.write('\n=== Public key written to src/services/guardian-agent/guardianSigningKey.ts (commit it) ===\n');
process.stdout.write(`keyId: ${keyId}\n`);
